export function getPackage(slug: string | undefined) {
  return packages.find((item) => item.slug === slug);
}

export function packagesForDestination(slug: string) {
  return packages.filter((item) => item.destinationSlug === slug);
}

export function relatedPackages(current: TripPackage, limit = 3) {
  const same = packages.filter((item) => item.slug !== current.slug && item.destinationSlug === current.destinationSlug);
  const rest = packages.filter((item) => item.slug !== current.slug && item.destinationSlug !== current.destinationSlug);
  return [...same, ...rest].slice(0, limit);
}
